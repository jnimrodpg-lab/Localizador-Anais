// El caso de dos extremos dentro de entrantes, unidos a través de un espacio exterior.
assert.equal(context.v209ZoneInsideArea([{x:220,y:50},{x:235,y:50},{x:235,y:210},{x:220,y:210}],concave),false,'La arista que atraviesa un entrante exterior se rechaza.');
assert.equal(context.v209AreaMetrics().count,2);
assert.equal(context.v209AreaMetrics().total,7.5);
assert.ok(Math.abs(context.v209AreaMetrics().assigned-(120*120+100*120)/10000)<1e-9);
assert.equal(context.v209AreaMetrics().invalid,0);
