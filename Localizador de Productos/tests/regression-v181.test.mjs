import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join,dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const layout=readFileSync(join(root,'src/frontend/60-layout-editor.js'),'utf8');
const geometry=readFileSync(join(root,'src/frontend/10-products-geometry.js'),'utf8');
const visual=readFileSync(join(root,'src/frontend/75-virtual-space.js'),'utf8');
const main=readFileSync(join(root,'public/assets/app-main.runtimefix.js'),'utf8');
assert.ok(layout.includes("const overlayLayer = svgEl('g'") && layout.includes('vertexLayer, overlayLayer, streetHandleLayer'), 'El overlay de selección no se ha inicializado antes de utilizarlo.');
assert.ok(layout.includes("svg.onpointerdown = handleLayoutCanvasDown") && !layout.includes("svg.addEventListener('pointerdown', handleLayoutCanvasDown)"),'Manejadores de canvas acumulativos.');
assert.ok(layout.includes('rpZoneFloor') && visual.includes('data-vs-zone-floor'), 'Faltan opciones de piso bidireccionales.');
assert.ok(visual.includes('new THREE.CanvasTexture(canvas)') && visual.includes('zone.floorFinish'), 'Los acabados no se renderizan en 3D.');
assert.ok(layout.includes('street-vertex-handle') && layout.includes('rpStreetReset') && geometry.includes('applyStreetVertexOffsets'),'Edición persistente de vértices incompleta.');
assert.ok(main.includes('layout-overlay-layer') && main.includes('street-vertex-handle') && main.includes('FLOOR_FINISHES'),'El bundle no incluye las correcciones.');
// Geometría aislada: la deformación editada debe sobrevivir a cambiar anchos y recalcular intersecciones.
const a=geometry.indexOf('  const FLOOR_FINISHES = Object.freeze(');
const b=geometry.indexOf('  function unitsToCm(',a);
assert.ok(a>0&&b>a);
const layoutState={meta:{defaultStreetCornerStyle:'right'},streets:[{id:'C1',side:'top',roadWidth:92,sidewalkWidth:42,cornerStyle:'right'},{id:'C2',side:'left',roadWidth:92,sidewalkWidth:42,cornerStyle:'right'}]};
const context={appState:{layout:layoutState},ensureLayoutMeta:()=>layoutState.meta,layoutBoundaryBounds:()=>({minX:0,minY:0,maxX:600,maxY:400}),nextStreetId:()=>`C${layoutState.streets.length+1}`};
const api=vm.runInNewContext(`${geometry.slice(a,b)}\n ({rebuildStreetNetwork,buildStreetGeometry,isValidStreetPolygon})`,context);
api.rebuildStreetNetwork();
const top=layoutState.streets.find(s=>s.id==='C1');
assert.ok(top.roadPts[0].x < 0,'Las calles no se proyectan hasta la intersección vecina.');
assert.ok(api.isValidStreetPolygon(top.roadPts),'Geometría vial inicial inválida.');
top.vertexOffsets={roadPts:{0:{dx:8,dy:-7}}};
api.rebuildStreetNetwork();
const modified=layoutState.streets.find(s=>s.id==='C1');
assert.ok(api.isValidStreetPolygon(modified.roadPts),'La edición deformó la calzada hasta una geometría inválida.');
const x=modified.roadPts[0].x,y=modified.roadPts[0].y;
modified.roadWidth=122;api.rebuildStreetNetwork();
assert.ok(Math.abs(layoutState.streets[0].roadPts[0].x-x)<.001,'El vértice editado desaparece tras modificar el ancho.');
assert.ok(Math.abs(layoutState.streets[0].roadPts[0].y-y+30)<.001,'El vértice no conserva el ajuste cuando cambia el ancho perpendicular.');
console.log('V181 OK: overlay, eventos no duplicados, porcelanatos y vértices persistentes tras reconstrucción.');
