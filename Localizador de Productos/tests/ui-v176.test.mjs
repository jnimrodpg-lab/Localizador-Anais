import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const layout=read('src/frontend/60-layout-editor.js');
const sheet=read('src/frontend/40-sheet-viewer-tools.js');
const main=read('public/assets/app-main.runtimefix.js');
const css=read('public/assets/app.css');
const core=read('src/styles/base.css');
const modern=read('src/styles/modern.css');
assert.ok(!layout.includes('Ver en 3D') && !layout.includes('btnOpenLayout3D') && !layout.includes('ctx-open-3d'), 'El editor CAD aún contiene el botón retirado.');
assert.ok(layout.includes('btnToggleSections') && layout.includes('layoutSectionSvgY'), 'Cortes X/Y o control ausente.');
assert.ok(!layout.includes('layoutV163Styles'), 'Inyección CSS heredada en el layout.');
assert.ok(layout.includes('Sin racks intersectados por el corte'), 'Falta estado vacío legible de cortes.');
assert.ok(!sheet.includes('branches-panel sheet-config-container'), 'Contenedor negro antiguo reapareció.');
assert.ok(sheet.includes('sheet-headers-disclosure'), 'Falta disclosure de encabezados.');
assert.ok(modern.includes('grid-template-columns:repeat(2,minmax(0,1fr))') && modern.includes('sheet-config-list'), 'Faltan reglas de estructura responsive.');
assert.equal(css.trim(),(core+'\n\n'+modern).trim(),'El CSS desplegado no coincide con su fuente.');
assert.ok(main.includes('renderSectionAxisSvg') && main.includes('sheet-config-list'), 'El bundle de JavaScript está incompleto.');
const html=read('public/index.html');
assert.ok(html.includes('WMS V190') && html.includes('wms-v190-zocalos-fondos-historial'), 'Versión del despliegue no identificable.');
assert.ok(read('wrangler.toml').includes('[[d1_databases]]') && fs.existsSync(path.join(root,'functions/api/[[path]].js')), 'Wrangler / D1 incompletos.');
console.log('V190 UI básica OK: CAD sin botón retirado, Sheets sin marco obsoleto, cortes, CSS coherente, Cloudflare D1 preservado.');
