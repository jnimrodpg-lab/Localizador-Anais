import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../src/frontend/60-layout-editor.js',import.meta.url),'utf8');
const start=source.indexOf('  function zoneBoundaryDistance(');
const end=source.indexOf('  function clearZoneCollisionPreview(',start);
assert.ok(start>=0&&end>start,'No se encontró el motor geométrico de zonas virtuales.');
const rectangle=(x1,y1,x2,y2)=>[{x:x1,y:y1},{x:x2,y:y1},{x:x2,y:y2},{x:x1,y:y2}];
const area=rectangle(0,0,300,250);
const z1={id:'Z1',pts:rectangle(0,0,120,120)};
const z2={id:'Z2',pts:rectangle(120,0,220,120)};
const layout={zones:[z1,z2],walls:[{id:'W1',ownerAreaId:'AREA-GENERAL',x1:0,y1:0,x2:300,y2:0}],racks:[{id:'R1',zoneId:'Z1'}],meta:{scaleCmPerUnit:1,siteBoundary:{pts:area}}};
const pointInPoly=(p,poly)=>{let inside=false;for(let i=0,j=poly.length-1;i<poly.length;j=i++) {const a=poly[i],b=poly[j];if((a.y>p.y)!==(b.y>p.y) && p.x<(b.x-a.x)*(p.y-a.y)/(b.y-a.y)+a.x)inside=!inside;}return inside;};
const polygonAreaAbs=pts=>Math.abs(pts.reduce((v,p,i)=>v+p.x*pts[(i+1)%pts.length].y-pts[(i+1)%pts.length].x*p.y,0)/2);
const polygonCentroid=pts=>({x:pts.reduce((s,p)=>s+p.x,0)/pts.length,y:pts.reduce((s,p)=>s+p.y,0)/pts.length});
const projectPointToSegment=(p,a,b)=>{const vx=b.x-a.x,vy=b.y-a.y,len=vx*vx+vy*vy||1,t=Math.max(0,Math.min(1,((p.x-a.x)*vx+(p.y-a.y)*vy)/len));return {x:a.x+t*vx,y:a.y+t*vy,t};};
const context={Math,Number,Array,Map,Set,pointInPoly,polygonAreaAbs,polygonCentroid,projectPointToSegment,appState:{layout}};
vm.createContext(context);vm.runInContext(source.slice(start,end),context);
const invalid=(id,pts,l=layout)=>context.v209ZoneViolation(id,pts,l);
assert.equal(invalid('Z1',z1.pts),null,'Zona compartiendo contorno del área es válida.');
assert.equal(invalid('Z2',z2.pts),null,'Dos zonas colindantes no se intersectan.');
assert.equal(invalid('Z2',rectangle(115,0,230,120)).reason,'overlap','No se puede invadir el interior vecino.');
assert.equal(invalid('Z2',rectangle(120,0,310,100)).reason,'outside','No se puede salir del local.');
assert.equal(invalid('Z2',rectangle(120,120,180,220)),null,'Puede existir una zona que solo comparta un borde.');
assert.equal(invalid('Z1',[{x:10,y:10},{x:100,y:100},{x:100,y:10},{x:10,y:100}]).reason,'invalid','La zona autointersectada se rechaza.');
const concave=[{x:0,y:0},{x:300,y:0},{x:300,y:80},{x:120,y:80},{x:120,y:180},{x:300,y:180},{x:300,y:250},{x:0,y:250}];
